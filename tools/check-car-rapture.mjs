import {register} from 'node:module';
import assert from 'node:assert/strict';
const base=new URL('../',import.meta.url).href;
register('data:text/javascript,'+encodeURIComponent(`export async function resolve(s,c,next){if(s==='three')return {url:${JSON.stringify(base)}+'lib/build/three.module.js',shortCircuit:true};if(s.startsWith('three/addons/'))return {url:${JSON.stringify(base)}+'lib/examples/jsm/'+s.slice(13),shortCircuit:true};return next(s,c)}`),import.meta.url);
const THREE=await import('three');
const {Traffic}=await import('../src/traffic.js');
const {BlessingEffects}=await import('../src/blessing-effects.js');
const scene=new THREE.Scene(),effects=new BlessingEffects(scene,{riderHalo:false});
const traffic=Object.create(Traffic.prototype), geometry=new THREE.BoxGeometry(2,1.5,4),material=new THREE.MeshStandardMaterial();
const inst=new THREE.InstancedMesh(geometry,material,2);scene.add(inst);
const car={type:'sedan',slot:0,active:true,x:0,y:0,z:0,v:20,dx:0,dz:-1,width:2,len:4};
const neighbour={...car,slot:1,x:20};
Object.assign(traffic,{cars:[car,neighbour],meshes:{sedan:{instances:[inst]}},matrices:{dummy:new THREE.Object3D()},blessingEffects:effects,nearMissEvents:[],crashRel:8.5});
const player={pos:new THREE.Vector3(.8,0,0),mods:{invuln:true},v:12,heading:0,shake:0};
assert.equal(traffic.checkPlayer(player,true),null);
assert.equal(car.ascended,true);assert.equal(car.active,false);assert.equal(neighbour.active,true);
assert.equal(player.v,12);assert.equal(player.pos.x,.8);assert.equal(player.shake,0);
assert.equal(effects.ascensions.length,1);assert.equal(effects.ascensions[0].root.children[0].geometry,geometry);
assert.equal(traffic.rapture(car),false);assert.equal(effects.ascensions.length,1);
let disposed=0;geometry.addEventListener('dispose',()=>disposed++);
effects.updateAscensions(1);assert(effects.ascensions[0].root.position.y>2);
const originalRandom=Math.random;Math.random=()=>0;let spawns=0;traffic.spawnNear=()=>spawns++;neighbour.active=false;traffic.checkPlayer=()=>null;
traffic.update(.01,player,false);Math.random=originalRandom;
assert.equal(spawns,1,'ascended slot excluded from respawning, other slot remains available');
traffic.resetAscensions();assert.equal(car.ascended,false);assert.equal(effects.ascensions.length,0);assert.equal(disposed,0);
console.log('PASS blessed car ascends once, no crash/scrape, neighbouring instance preserved, no respawn until reset, shared geometry retained');
