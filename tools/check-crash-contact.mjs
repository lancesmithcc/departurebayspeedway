import { register } from 'node:module';
import assert from 'node:assert/strict';
const base = new URL('../', import.meta.url).href;
register('data:text/javascript,' + encodeURIComponent(`export async function resolve(s,c,next){if(s==='three')return {url:${JSON.stringify(base)}+'lib/build/three.module.js',shortCircuit:true};if(s.startsWith('three/addons/'))return {url:${JSON.stringify(base)}+'lib/examples/jsm/'+s.slice(13),shortCircuit:true};return next(s,c)}`), import.meta.url);
const THREE = await import('three');
const { Player, sweepBuildingContact } = await import('../src/player.js');
const { Grid } = await import('../src/util.js');
const grid = new Grid(24);
const building = { pts: [[0,-6],[.08,-6],[.08,6],[0,6]], x0:0,x1:.08,z0:-6,z1:6,gy:0,h:8 };
grid.insertAABB(0,-6,.08,6,building);
const v = (x,y,z) => new THREE.Vector3(x,y,z);
let hit = sweepBuildingContact(grid,v(-12,0,0),v(15,0,0),.7);
assert(hit && Math.abs(hit.x + .7) < 1e-8 && hit.nx === -1, 'high speed sweep stops before thin facade');
assert.equal(sweepBuildingContact(grid,v(-12,10,0),v(15,10,0),.7),null,'jump above roof stays clear');
hit = sweepBuildingContact(grid,v(.04,0,0),v(2,0,0),.7);
assert(hit && (hit.x < -.7 || hit.x > .78),'embedded spawn is expelled outward');
hit = sweepBuildingContact(grid,v(-2,0,-7),v(2,0,-5),.7);
assert(hit && hit.nx < 0 && hit.nz < 0,'rounded corner contact has diagonal normal');
const terrain = { groundHeight:()=>-5, meshHeight:()=>0, roadDeck:()=>({y:.07,d:0,hw:5}) };
const player = Object.create(Player.prototype);
Object.assign(player,{terrain,ctx:{buildingGrid:grid,callbacks:{},effects:null},pos:v(-4,.07,0),heading:-Math.PI/2,v:30,vy:0,offroad:false,state:'crashed',crashT:0,crashDir:v(1,0,0),crashRoll:0,crashSide:1,crashYaw:0,crashPitch:0,shake:0,root:new THREE.Group()});
player.root.add(new THREE.Mesh(new THREE.BoxGeometry(1,1,2),new THREE.MeshBasicMaterial()));
assert.equal(player.groundAt(0,0),.07,'uses asphalt deck above carved terrain');
for(let i=0;i<20;i++)player.update(.1,{});
assert(player.pos.x < -.95 && player.v === 0,'crashed body stops at wall and never slides through');
player.cameraMode=3;player.heading=Math.PI/2;player.v=0;
const camera=new THREE.PerspectiveCamera();
player.updateCamera(camera,1/60,0);
assert(camera.position.x < -.3,'initial title camera cannot enter building');
const initial=camera.position.clone();
player.updateCamera(camera,1/60,999);
assert(camera.position.distanceTo(initial)<1e-10,'title stays still as time advances');
player.cameraMode=0;camera.position.set(4,2,0);
player.updateCamera(camera,1/60,1000);
assert(camera.position.x < -.3,'chase interpolation corrected before rendering behind wall');
console.log('PASS: thin-wall sweep, roof clearance, corner contact, outward recovery, crash momentum, rendered ground, fixed title and chase occlusion');

const {Game}=await import('../src/game.js');
let titleCalls=0;
Game.prototype.titleCamera.call({player:{cameraMode:0,updateCamera(camera,dt,time){assert.equal(this.cameraMode,3);assert.equal(dt,0);titleCalls++;}},camera:{}},100);
assert.equal(titleCalls,1,'game intro uses fixed player camera instead of orbit');
