import {register} from 'node:module';
import assert from 'node:assert/strict';
const base=new URL('../',import.meta.url).href;
register('data:text/javascript,'+encodeURIComponent(`export async function resolve(s,c,next){if(s==='three')return {url:${JSON.stringify(base)}+'lib/build/three.module.js',shortCircuit:true};if(s.startsWith('three/addons/'))return {url:${JSON.stringify(base)}+'lib/examples/jsm/'+s.slice(13),shortCircuit:true};return next(s,c)}`),import.meta.url);
const THREE=await import('three');
const {BarThrower}=await import('../src/nanaimo.js');
const {Police}=await import('../src/police.js');
const scene=new THREE.Scene();let voices=0,shots=0,scored=0;
const police=new Police(scene,{renderedGroundHeight:()=>0},{audio:{voice:(key)=>{assert.equal(key,'police_defeated');voices++;}},onShot:()=>shots++});
const car={type:'rcmp',active:true,gen:1,x:0,y:0,z:0,heading:0,v:0};
assert(police.trigger(car));
const target=police.encounters[0].officer.position;
const thrower=Object.create(BarThrower.prototype);
const bar={active:true,life:3,pos:new THREE.Vector3(target.x,1,target.z+3),vel:new THREE.Vector3(0,0,-60),spin:new THREE.Vector3(),mesh:new THREE.Object3D()};
Object.assign(thrower,{police,traffic:{cars:[]},audio:{splat(){}},onOfficerHit:()=>scored++,previousBarPosition:new THREE.Vector3(),bars:[bar],splats:[],cool:0,hits:0});
thrower.update(.1,{});
assert.equal(thrower.hits,1);assert.equal(scored,1);assert.equal(voices,1);assert.equal(bar.active,false);assert.equal(bar.mesh.visible,false);
for(let i=0;i<80;i++)police.update(.1,{pos:new THREE.Vector3(target.x,0,target.z-8)},true);
assert.equal(shots,0,'defeated officer cannot fire');
assert.equal(voices,1,'reaction never repeats');
thrower.reset();police.reset();assert.equal(scene.children.length,0);
assert(police.trigger(car));
let ascensions=0;const e=police.encounters[0];
assert.equal(police.raptureTouch(e.officer.position,{ascend:()=>ascensions++}),1);
police.update(.1,{pos:e.officer.position.clone()},true);
assert.equal(e.officer.visible,false);assert.equal(ascensions,1);assert.equal(voices,1);assert.equal(shots,0);
assert.equal(police.hitSegment(e.officer.position,e.officer.position),null);police.reset();
console.log('PASS fast bar sweep defeats officer, consumes projectile, scores once, speaks once, stops firing and resets');
